MODEL_LINE = re.compile(r'("HF_FINETUNED_MODEL",\s*\n\s*")([^"]+)(")')


def main() -> int:
    root = Path.cwd()
    if not (root / "src" / "config.py").exists():
        print("ERROR: run from the repository root (src/config.py not found).")
        return 1
    sentiment = root / "src" / "engine" / "sentiment.py"
    current_model = None
    if sentiment.exists():
        m = MODEL_LINE.search(sentiment.read_text(encoding="utf-8"))
        current_model = m.group(2) if m else None

    backup = root / ".pre_fix_backup" / ("v2_3-" + time.strftime("%Y%m%d-%H%M%S"))
    archive = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(PAYLOAD.split()))))
    names = [n for n in archive.namelist() if not n.endswith("/")]
    for name in names:
        target = root / name
        if target.exists():
            dest = backup / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, dest)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(archive.read(name))

    if current_model and sentiment.exists():
        text = sentiment.read_text(encoding="utf-8")
        sentiment.write_text(MODEL_LINE.sub(lambda m: m.group(1) + current_model + m.group(3), text),
                             encoding="utf-8")
        print(f"Kept your sentiment model: {current_model}")

    for cache in root.rglob("__pycache__"):
        if ".venv" not in cache.parts and "venv" not in cache.parts:
            shutil.rmtree(cache, ignore_errors=True)
    print(f"Updated {len(names)} files (backup: {backup})")
    for n in names:
        print("  " + n)
    print("\nNext:  python -m pytest -q   (expect 49 passed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
