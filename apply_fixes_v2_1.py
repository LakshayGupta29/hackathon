def main() -> int:
    root = Path.cwd()
    if not (root / "src" / "config.py").exists():
        print("ERROR: run from the repository root, after apply_fixes.py (src/config.py not found).")
        return 1
    backup = root / ".pre_fix_backup" / ("v2_1-" + time.strftime("%Y%m%d-%H%M%S"))
    archive = zipfile.ZipFile(io.BytesIO(base64.b64decode("".join(PAYLOAD.split()))))
    names = [n for n in archive.namelist() if not n.endswith("/")]
    for name in names:
        target = root / name
        if target.exists():
            dest = backup / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, dest)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(archive.read(name))
    for cache in root.rglob("__pycache__"):
        if ".venv" not in cache.parts and "venv" not in cache.parts:
            shutil.rmtree(cache, ignore_errors=True)
    print(f"Updated {len(names)} files (backup: {backup})")
    for n in names:
        print("  " + n)
    print("\nNext:  python -m pytest -q   (expect 48 passed), then restart the API")
    return 0


if __name__ == "__main__":
    sys.exit(main())
